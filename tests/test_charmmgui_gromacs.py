def test_prepared_run_folder_is_writable_when_download_is_read_only(tmp_path):
    download, _ = _write_solution_builder(tmp_path / "download")
    toppar = download / "gromacs" / "toppar"
    for path in toppar.iterdir():
        path.chmod(0o444)
    toppar.chmod(0o555)
    try:
        run = prepare_charmm_gui_run_folder(download, tmp_path / "run")
        (run / "toppar" / "LIG.itp").write_text("editable\n")
        (run / "toppar" / "new.itp").write_text("")
    finally:
        toppar.chmod(0o755)
        for path in toppar.iterdir():
            path.chmod(0o644)
