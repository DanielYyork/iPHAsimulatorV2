def _write_ligand_reader(folder, smiles=R_LIGAND):
    (folder / "gromacs").mkdir(parents=True)
    ligand = _embedded(smiles)
    itp, names = _ligand_itp(ligand)
    (folder / "gromacs" / "charmm36.itp").write_text(FORCEFIELD_ITP)
    (folder / "gromacs" / "LIG.itp").write_text(itp)
    (folder / "gromacs" / "topol.top").write_text(
        '#include "charmm36.itp"\n#include "LIG.itp"\n[ system ]\nTitle\n[ molecules ]\nLIG 1\n'
    )
    pdb = []
    for index, (name, (x, y, z)) in enumerate(zip(names, ligand.GetConformer().GetPositions()), start=1):
        pdb.append(f"ATOM  {index:5d} {name:<4} LIG L   1    {x:8.3f}{y:8.3f}{z:8.3f}  1.00  0.00      LIG")
    (folder / "ligandrm.pdb").write_text("\n".join(pdb) + "\nEND\n")
    sdf = folder / "ligand.sdf"
    Chem.MolToMolFile(ligand, str(sdf))
    return folder, sdf


def test_prepare_and_validate_dry_ligand_folder(tmp_path):
    download, sdf = _write_ligand_reader(tmp_path / "lrm")

    dry = prepare_dry_ligand_folder(download, tmp_path / "dry", padding_nm=1.7)

    assert {p.name for p in dry.iterdir()} == {"topol.top", "charmm36.itp", "LIG.itp", "lig.gro", "dry_minimization.mdp"}
    box = float((dry / "lig.gro").read_text().splitlines()[-1].split()[0])
    assert box > 3.4  # molecule extent + 2 * padding
    results = validate_dry_ligand_folder(dry, sdf_path=sdf)
    assert all(result.status == "PASS" for result in results), format_checks(results)


MDRUN_LOG_TAIL = """
Steepest Descents converged to Fmax < 100 in 212 steps
Potential Energy  = -1.2345678e+02
Maximum force     =  9.8765432e+01 on atom 12
Norm of force     =  2.0000000e+01
"""


def test_run_dry_minimization_calls_grompp_then_mdrun_and_reads_log(tmp_path):
    download, _ = _write_ligand_reader(tmp_path / "lrm")
    dry = prepare_dry_ligand_folder(download, tmp_path / "dry")
    calls = []

    def fake_runner(command, cwd, **kwargs):
        calls.append(command[:2])
        if command[1] == "mdrun":
            (cwd / "dry_minimization.log").write_text(MDRUN_LOG_TAIL)
        return subprocess.CompletedProcess(command, 0, "", "")

    result = run_dry_minimization(dry, runner=fake_runner)

    assert calls == [["gmx", "grompp"], ["gmx", "mdrun"]]
    assert result.potential_energy == pytest.approx(-123.45678)
    assert result.maximum_force == pytest.approx(98.765432)


def test_run_dry_minimization_reports_gmx_failure(tmp_path):
    download, _ = _write_ligand_reader(tmp_path / "lrm")
    dry = prepare_dry_ligand_folder(download, tmp_path / "dry")

    def failing_runner(command, cwd, **kwargs):
        return subprocess.CompletedProcess(command, 1, "", "Fatal error: something")

    with pytest.raises(RuntimeError, match="Fatal error"):
        run_dry_minimization(dry, runner=failing_runner)


