R_LIGAND = "C[C@@H](O)CC(=O)O"  # (R)-3-hydroxybutanoic acid
S_LIGAND = "C[C@H](O)CC(=O)O"
TYPE_BY_ELEMENT = {"C": "CG321", "O": "OG311", "H": "HGA2"}
MASS_BY_ELEMENT = {"C": 12.011, "O": 15.9994, "H": 1.008}

FORCEFIELD_ITP = """[ defaults ]
; nbfunc	comb-rule	gen-pairs	fudgeLJ	fudgeQQ
1	2	yes	1.0	1.0
"""
TIP3_ITP = """[ moleculetype ]
TIP3 2
[ atoms ]
1 OT 1 TIP3 OH2 1 -0.834 15.9994
2 HT 1 TIP3 H1 2 0.417 1.008
3 HT 1 TIP3 H2 3 0.417 1.008
"""
IONS_ITP = """[ moleculetype ]
SOD 0
[ atoms ]
1 SOD 1 SOD SOD 1 1.000 22.98977
[ moleculetype ]
CLA 0
[ atoms ]
1 CLA 1 CLA CLA 1 -1.000 35.45
"""


def _embedded(smiles):
    mol = Chem.AddHs(Chem.MolFromSmiles(smiles))
    AllChem.EmbedMolecule(mol, randomSeed=7)
    return mol


def _ligand_itp(mol, types=None):
    names = [f"{atom.GetSymbol()}{atom.GetIdx() + 1}" for atom in mol.GetAtoms()]
    lines = ["[ moleculetype ]", "LIG 3", "[ atoms ]"]
    for atom, name in zip(mol.GetAtoms(), names):
        element = atom.GetSymbol()
        atom_type = (types or TYPE_BY_ELEMENT)[element]
        lines.append(
            f"{atom.GetIdx() + 1} {atom_type} 1 LIG {name} {atom.GetIdx() + 1} 0.000 {MASS_BY_ELEMENT[element]}"
        )
    lines.append("[ bonds ]")
    lines += [f"{bond.GetBeginAtomIdx() + 1} {bond.GetEndAtomIdx() + 1} 1" for bond in mol.GetBonds()]
    return "\n".join(lines) + "\n", names


def _gro_line(residue_number, residue, name, index, xyz_nm):
    x, y, z = xyz_nm
    return f"{residue_number:5d}{residue:<5}{name:>5}{index:5d}{x:8.3f}{y:8.3f}{z:8.3f}"


def _write_solution_builder(folder, smiles=R_LIGAND, wrap_first_atom=False):
    """A tiny Solution Builder-like gromacs/ folder: LIG + 1 TIP3 + SOD + CLA."""

    gromacs = folder / "gromacs"
    (gromacs / "toppar").mkdir(parents=True)
    ligand = _embedded(smiles)
    itp, names = _ligand_itp(ligand)
    (gromacs / "toppar" / "forcefield.itp").write_text(FORCEFIELD_ITP)
    (gromacs / "toppar" / "LIG.itp").write_text(itp)
    (gromacs / "toppar" / "TIP3.itp").write_text(TIP3_ITP)
    (gromacs / "toppar" / "ions.itp").write_text(IONS_ITP)
    (gromacs / "topol.top").write_text(
        '#include "toppar/forcefield.itp"\n#include "toppar/LIG.itp"\n'
        '#include "toppar/TIP3.itp"\n#include "toppar/ions.itp"\n'
        "[ system ]\nTitle\n[ molecules ]\nLIG 1\nTIP3 1\nSOD 1\nCLA 1\n"
    )
    box = 3.0
    positions = ligand.GetConformer().GetPositions() / 10 + 1.5
    if wrap_first_atom:
        positions[0][0] += box  # molecule split across the periodic boundary
    lines = [_gro_line(1, "LIG", name, i + 1, xyz) for i, (name, xyz) in enumerate(zip(names, positions))]
    n = len(lines)
    lines += [
        _gro_line(2, "TIP3", "OH2", n + 1, (0.2, 0.2, 0.2)),
        _gro_line(2, "TIP3", "H1", n + 2, (0.3, 0.2, 0.2)),
        _gro_line(2, "TIP3", "H2", n + 3, (0.2, 0.3, 0.2)),
        _gro_line(3, "SOD", "SOD", n + 4, (2.5, 2.5, 2.5)),
        _gro_line(4, "CLA", "CLA", n + 5, (2.5, 0.5, 2.5)),
    ]
    (gromacs / "step3_input.gro").write_text(
        "Generated by test\n" + f"{len(lines):5d}\n" + "\n".join(lines) + f"\n{box:10.5f}{box:10.5f}{box:10.5f}\n"
    )
    (gromacs / "index.ndx").write_text(f"[ SOLU ]\n{' '.join(str(i) for i in range(1, n + 1))}\n[ SOLV ]\n{n + 1} {n + 2} {n + 3}\n")
    (gromacs / "step4.0_minimization.mdp").write_text("integrator = steep\n")
    (gromacs / "step5_production.mdp").write_text("integrator = md\n")
    sdf = folder / "ligand.sdf"
    Chem.MolToMolFile(_embedded(R_LIGAND), str(sdf))
    return folder, sdf


def _status(results, prefix):
    return next(result.status for result in results if result.name.startswith(prefix))


def test_prepare_charmm_gui_run_folder_follows_production_layout(tmp_path):
    download, _ = _write_solution_builder(tmp_path / "download")

    run = prepare_charmm_gui_run_folder(download, tmp_path / "run", job_name="PHO4_GK13")

    assert (run / "step5_input.gro").is_file()
    assert not (run / "step3_input.gro").exists()
    assert not (run / "step4.0_minimization.mdp").exists()
    assert not (run / "step5_production.mdp").exists()
    assert (run / "toppar" / "LIG.itp").is_file()
    for name in ("step6.0_minimization.mdp", "step6.1_nvt.mdp", "step6.2_npt.mdp", "step7_production.mdp"):
        assert (run / name).read_text() == (CHARMM_GROMACS_TEMPLATE_DIR / name).read_text()
    slurm = (run / "run_hpc_equilibration_production.slurm").read_text()
    assert "#SBATCH --job-name=PHO4_GK13" in slurm
    assert "{JOB_NAME}" not in slurm
    assert (download / "gromacs" / "step3_input.gro").is_file()  # source untouched


